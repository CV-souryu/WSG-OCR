"""Public FixedFontOCR API."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np
from numpy.typing import NDArray

from .backends import (
    AutoBackend,
    Backend,
    CPUBackend,
    WGPUBackend,
    benchmark_backends,
)
from .classifier import Classifier, TemplateClassifier
from .cnn import forward
from .model import load_model
from .postprocess import allowed_ids as build_allowed_ids
from .postprocess import pick
from .preprocess import find_lines, normalize
from .scorer import SegmentScorer, to_confidence
from .segmentation import segment_line
from .types import CharResult, OCRResult, Profile, default_profile

UNKNOWN_CHAR = "?"


@dataclass
class FixedFontOCR:
    """Fixed-font OCR engine.

    Parameters
    ----------
    model_path:
        Directory containing ``config.json``, ``charset.txt`` and
        ``weights.bin`` (generated by ``fixedfontocr-generate``).
    backend:
        ``"cpu"`` selects the numpy TinyCNN backend (or the template
        matcher), ``"wgpu"`` the WGPU compute backend for tinycnn/hybrid
        models. ``"auto"`` (default) benchmarks CPU vs WGPU at batch sizes
        1/8/16/32/64/128 during construction, records the crossover, and then
        picks the faster backend per actual batch size at runtime.
    profile:
        Segmentation profile. When ``None``, a default profile is used.
    auto_benchmark:
        Only used with ``backend="auto"``. When False the engine skips the
        startup benchmark and falls back to the CPU backend.
    auto_batch_sizes:
        Only used with ``backend="auto"``. Batch sizes measured during the
        startup benchmark.
    """

    model_path: str | Path
    backend: str = "auto"
    profile: Profile | None = None
    auto_benchmark: bool = True
    auto_batch_sizes: tuple[int, ...] = (1, 8, 16, 32, 64, 128)

    def __post_init__(self) -> None:
        if self.backend not in ("auto", "cpu", "wgpu"):
            raise ValueError(
                f"backend {self.backend!r} is not supported; use 'cpu', 'wgpu' or 'auto'"
            )
        self.model = load_model(Path(self.model_path))
        self.profile = self.profile or default_profile()
        self._scorer = SegmentScorer(self.model)
        self._benchmark: dict[int, dict[str, float]] | None = None
        self._benchmark_error: str | None = None
        self._backend: Backend | None = None

        if self.model.classifier in ("tinycnn", "hybrid"):
            self._backend: Backend = self._make_backend()
        else:
            if self.backend == "wgpu":
                raise ValueError(
                    "WGPU backend requires a tinycnn model; template models run on CPU"
                )
            self._classifier: Classifier = TemplateClassifier(
                templates=self.model.templates,
                charset=self.model.charset,
                input_size=self.model.input_size,
            )
        if self.model.classifier == "hybrid":
            self._template_classifier = TemplateClassifier(
                templates=self.model.templates,
                charset=self.model.charset,
                input_size=self.model.input_size,
            )
            self._template_threshold = float(
                self.model.config.get("template_threshold", 0.90)
            )
            self._cnn_threshold = float(
                self.model.config.get("cnn_threshold", 0.0)
            )

    # ------------------------------------------------------------------
    # Backend selection
    # ------------------------------------------------------------------

    def _make_backend(self) -> Backend:
        if self.backend == "wgpu":
            return WGPUBackend(
                weights=self.model.weights,
                input_size=self.model.input_size,
            )
        cpu = CPUBackend(
            weights=self.model.weights,
            input_size=self.model.input_size,
        )
        if self.backend == "cpu" or not self.auto_benchmark:
            return cpu
        try:
            gpu = WGPUBackend(
                weights=self.model.weights,
                input_size=self.model.input_size,
            )
        except Exception as exc:  # no adapter / driver
            self._benchmark_error = f"wgpu unavailable: {exc}"
            return cpu
        try:
            measurements = benchmark_backends(cpu, gpu, self.auto_batch_sizes)
        except Exception as exc:
            self._benchmark_error = f"backend benchmark failed: {exc}"
            return cpu
        self._benchmark = measurements
        return AutoBackend(cpu=cpu, gpu=gpu, measurements=measurements)

    @property
    def backend_benchmark(self) -> dict[int, dict[str, float]] | None:
        """CPU/GPU latency table measured at construction (``auto`` only)."""
        return self._benchmark

    @property
    def backend_benchmark_error(self) -> str | None:
        """Why ``auto`` fell back to CPU, if it did."""
        return self._benchmark_error

    @property
    def resolved_backend(self) -> str:
        """Backend name after auto-selection: ``cpu``, ``wgpu`` or ``auto``."""
        if self.backend != "auto":
            return self.backend
        if isinstance(self._backend, AutoBackend):
            return "auto"
        return "cpu"

    # ------------------------------------------------------------------
    # Recognition
    # ------------------------------------------------------------------

    def recognize(
        self,
        image: NDArray[np.uint8],
        allowed_chars: str | None = None,
    ) -> OCRResult:
        """Recognize horizontal, single-line text in ``image``.

        ``image`` must have shape ``(H, W, 3)`` and dtype ``uint8``.
        ``allowed_chars`` optionally restricts the classifier's output
        alphabet (e.g. ``"0123456789"`` for a coin counter). Characters
        outside the set are never emitted; when no candidate survives, the
        position is reported as ``"?"`` with confidence 0.
        """

        image = np.asarray(image)
        if image.ndim != 3 or image.shape[2] != 3:
            raise ValueError(f"expected RGB image with shape (H, W, 3), got {image.shape}")
        if image.dtype != np.uint8:
            raise ValueError(f"expected uint8 image, got {image.dtype}")

        allowed = build_allowed_ids(self.model.charset, allowed_chars)
        mask = self.profile.color_mask(image)
        chars: list[CharResult] = []
        for line in find_lines(mask, self.profile):
            path = segment_line(line, self.profile, self._scorer, allowed)
            if not path.candidates:
                continue
            segments = [c.segment for c in path.candidates]
            if self.model.classifier == "template":
                for seg in segments:
                    char, conf = self._classifier(seg.mask, self.profile, allowed)
                    chars.append(
                        CharResult(
                            char=char,
                            x=seg.x,
                            y=seg.y,
                            w=seg.w,
                            h=seg.h,
                            confidence=conf,
                        )
                    )
            else:
                glyphs = np.stack(
                    [normalize(s.mask, self.model.input_size) for s in segments]
                )
                if self.model.classifier == "hybrid":
                    chars.extend(self._recognize_hybrid(segments, glyphs, allowed))
                else:
                    result = self._backend.classify(glyphs)
                    chars.extend(
                        self._chars_from_backend(segments, glyphs, result, allowed)
                    )

        if not chars:
            return OCRResult(text="", confidence=0.0, chars=())
        text = "".join(c.char for c in chars)
        confidence = float(np.mean([c.confidence for c in chars]))
        return OCRResult(text=text, confidence=confidence, chars=tuple(chars))

    def _chars_from_backend(
        self,
        segments,
        glyphs: NDArray[np.uint8],
        result,
        allowed: set[int] | None,
    ) -> list[CharResult]:
        """Map a backend result to CharResults, masking disallowed picks."""
        n = len(segments)
        if n == 0:
            return []
        chars: list[CharResult | None] = [None] * n
        remask: list[int] = []
        for i, (seg, char_id, score) in enumerate(
            zip(segments, result.char_ids, result.scores)
        ):
            if allowed is None or int(char_id) in allowed:
                chars[i] = CharResult(
                    char=self.model.charset[int(char_id)],
                    x=seg.x,
                    y=seg.y,
                    w=seg.w,
                    h=seg.h,
                    confidence=to_confidence(float(score), "cnn"),
                )
            else:
                remask.append(i)
        if remask:
            idx = np.asarray(remask, dtype=np.int64)
            x = glyphs[idx].astype(np.float32)[:, None, :, :] * (1.0 / 255.0)
            logits = forward(x, self.model.weights)
            for k, i in enumerate(remask):
                char, conf = pick(logits[k], self.model.charset, allowed)
                seg = segments[i]
                chars[i] = CharResult(
                    char=char,
                    x=seg.x,
                    y=seg.y,
                    w=seg.w,
                    h=seg.h,
                    confidence=to_confidence(conf, "cnn"),
                )
        return [c for c in chars if c is not None]

    def _recognize_hybrid(
        self,
        segments,
        glyphs: NDArray[np.uint8],
        allowed: set[int] | None,
    ) -> list[CharResult]:
        """Three-level strategy: template (margin-gated) -> CNN -> unknown.

        Uses the same :class:`SegmentScorer` as the segmentation DP, so the
        final hybrid classification and the lattice share one margin-aware
        gate: a template match is trusted only when both its confidence and
        its top-1/top-2 margin are high.
        """

        if not segments:
            return []
        scores = self._scorer.score(segments, allowed)
        chars: list[CharResult] = []
        for seg, score in zip(segments, scores):
            if score.char_id < 0:
                char = UNKNOWN_CHAR
                conf = 0.0
            elif score.score_type == "cnn" and score.raw_score < self._cnn_threshold:
                char = UNKNOWN_CHAR  # Level 3: unknown
                conf = score.visual_score
            else:
                char = self.model.charset[int(score.char_id)]
                conf = score.visual_score
            chars.append(
                CharResult(
                    char=char,
                    x=seg.x,
                    y=seg.y,
                    w=seg.w,
                    h=seg.h,
                    confidence=conf,
                )
            )
        return chars
